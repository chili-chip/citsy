#!/usr/bin/env python3
"""Write src/font/builtin_fonts.cpp from Bitsy 8.15's .bitsyfont files.

Usage: python3 scripts/gen_builtin_fonts.py

Reads the fonts in tests/parity/reference/bitsy-8.15 the way Bitsy's font.js
does and packs each glyph's pixels into a bit array (row-major, most
significant bit first). tests/unit/test_textbox.cpp checks that the result
matches parse_bitsyfont() on the same files.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tests" / "parity" / "reference" / "bitsy-8.15"
OUTPUT = ROOT / "src" / "font" / "builtin_fonts.cpp"
FONTS = ["ascii_small", "unicode_european_small", "unicode_european_large", "arabic"]


def parse(text):
    """Port of font.js parseFont: returns (name, width, height, glyphs)."""
    name, width, height = "unknown", 6, 8
    glyphs = {}
    reading_char = False
    reading_props = False
    rows = 0
    code = 0
    for line in text.split("\n"):
        if line.startswith("#"):
            continue
        if not reading_char:
            args = line.split(" ")
            if args[0] == "FONT":
                name = args[1]
            elif args[0] == "SIZE":
                width, height = int(args[1]), int(args[2])
            elif args[0] == "CHAR":
                reading_char = True
                reading_props = True
                rows = 0
                code = int(args[1])
                glyphs[code] = {"w": width, "h": height, "ox": 0, "oy": 0,
                                "spacing": width, "bits": []}
            continue
        g = glyphs[code]
        if reading_props:
            args = line.split(" ")
            if args[0].startswith("CHAR_"):
                if args[0] == "CHAR_SIZE":
                    g["w"], g["h"] = int(args[1]), int(args[2])
                    g["spacing"] = int(args[1])
                elif args[0] == "CHAR_OFFSET":
                    g["ox"], g["oy"] = int(args[1]), int(args[2])
                elif args[0] == "CHAR_SPACING":
                    g["spacing"] = int(args[1])
                continue
            reading_props = False
        g["bits"].extend(1 if x < len(line) and line[x] == "1" else 0 for x in range(g["w"]))
        rows += 1
        if rows >= g["h"]:
            reading_char = False
    return name, width, height, glyphs


def ident(name):
    return "k" + "".join(part.capitalize() for part in name.split("_"))


def emit_font(out, font_name):
    name, width, height, glyphs = parse((SOURCE / f"{font_name}.bitsyfont").read_text())
    assert name == font_name, (name, font_name)
    base = ident(name)
    bits = []
    out.append(f"constexpr BuiltinGlyph {base}Glyphs[] = {{")
    for code in sorted(glyphs):
        g = glyphs[code]
        out.append(f"    {{{code}, {g['w']}, {g['h']}, {g['ox']}, {g['oy']}, "
                   f"{g['spacing']}, {len(bits)}}},")
        bits.extend(g["bits"])
    out.append("};")
    packed = []
    for i in range(0, len(bits), 8):
        chunk = bits[i:i + 8] + [0] * (8 - len(bits[i:i + 8]))
        packed.append(sum(b << (7 - j) for j, b in enumerate(chunk)))
    out.append(f"constexpr std::uint8_t {base}Bits[] = {{")
    for i in range(0, len(packed), 16):
        out.append("    " + ",".join(f"0x{b:02x}" for b in packed[i:i + 16]) + ",")
    out.append("};")
    out.append("")
    return f'    {{"{name}", {width}, {height}, {base}Glyphs, {base}Bits}},'


def main():
    out = [
        "// Generated by scripts/gen_builtin_fonts.py from Bitsy 8.15's fonts. Do not edit.",
        "// Font data from Bitsy (MIT, Copyright (c) 2016-present, Bitsy authors);",
        "// see the Bitsy notice in LICENSE.",
        "",
        '#include "src/font/builtin_fonts.hpp"',
        "",
        "namespace citsy {",
        "namespace {",
        "",
    ]
    entries = [emit_font(out, name) for name in FONTS]
    out.append("} // namespace")
    out.append("")
    out.append("std::span<const BuiltinFont> builtin_font_table() {")
    out.append("    static constexpr BuiltinFont kFonts[] = {")
    out.extend("    " + e for e in entries)
    out.append("    };")
    out.append("    return kFonts;")
    out.append("}")
    out.append("")
    out.append("} // namespace citsy")
    OUTPUT.write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
